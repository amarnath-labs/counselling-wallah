import "dotenv/config";
import fs from "node:fs/promises";
import { pool } from "./src/db/pool.js";

const INPUT =
  "./all-db-colleges-fee-input.json";

const OUTPUT =
  "./all-colleges-fee-source-family.json";

const JOSAA_OUTPUT =
  "./all-colleges-josaa-fee-queue.json";

const UPTAC_OUTPUT =
  "./all-colleges-uptac-fee-queue.json";

const OTHER_OUTPUT =
  "./all-colleges-other-fee-queue.json";

/*
|--------------------------------------------------------------------------
| COMPLETED
|--------------------------------------------------------------------------
*/

const COMPLETED = new Set([
  "uptac-ajay-kumar-garg-engg-college-ghaziabad",
  "uptac-abss-institute-of-technology-meerut-meerut",
  "uptac-ashoka-institute-of-technology-management-varanasi",
  "uptac-accurate-institute-of-management-technology-gautam-buddh-nagar"
]);

/*
|--------------------------------------------------------------------------
| HELPERS
|--------------------------------------------------------------------------
*/

function clean(value) {
  return String(value ?? "")
    .trim();
}

function lower(value) {
  return clean(value)
    .toLowerCase();
}

/*
|--------------------------------------------------------------------------
| JoSAA detection
|--------------------------------------------------------------------------
|
| Covers:
| IIT
| NIT
| IIIT
| IISc
| IIEST
| GFTIs / central institutes commonly present in JoSAA data
|--------------------------------------------------------------------------
*/

function isJosaaCollege(name) {
  const n = lower(name);

  return (
    /\bindian institute of technology\b/.test(n) ||
    /\biit\b/.test(n) ||

    /\bnational institute of technology\b/.test(n) ||
    /\bnit\b/.test(n) ||

    /\bindian institute of information technology\b/.test(n) ||
    /\biiit\b/.test(n) ||

    /indian institute of science/.test(n) ||

    /indian institute of engineering science and technology/.test(n) ||
    /\biiest\b/.test(n) ||

    /school of planning\s*&?\s*architecture/.test(n) ||

    /sant longowal institute/.test(n) ||

    /ghani khan choudhary institute/.test(n) ||

    /central institute of technology kokrajar/.test(n) ||

    /gurukula kangri/.test(n) ||

    /tezpur university/.test(n) ||

    /guru ghasidas/.test(n) ||

    /mizoram university/.test(n) ||

    /assam university/.test(n) ||

    /central university/.test(n)
  );
}

/*
|--------------------------------------------------------------------------
| UPTAC detection
|--------------------------------------------------------------------------
|
| Strongest signal is college ID generated by UPTAC importer.
|--------------------------------------------------------------------------
*/

function isUptacCollege(row) {
  return (
    String(
      row.college_id || ""
    )
      .toLowerCase()
      .startsWith(
        "uptac-"
      )
  );
}

/*
|--------------------------------------------------------------------------
| CLASSIFY
|--------------------------------------------------------------------------
*/

function classify(row) {
  if (
    COMPLETED.has(
      row.college_id
    )
  ) {
    return {
      ...row,

      source_family:
        "COMPLETED",

      source_strategy:
        "SKIP_ALREADY_IMPORTED"
    };
  }

  /*
  |--------------------------------------------------------------------------
  | Prefer UPTAC ID when present.
  |--------------------------------------------------------------------------
  */

  if (
    isUptacCollege(row)
  ) {
    return {
      ...row,

      source_family:
        "UPTAC",

      source_strategy:
        "UPTAC_2026_OR_OFFICIAL_INSTITUTE"
    };
  }

  if (
    isJosaaCollege(
      row.college_name
    )
  ) {
    return {
      ...row,

      source_family:
        "JOSAA",

      source_strategy:
        "JOSAA_2026_OFFICIAL_FEE_DETAILS"
    };
  }

  return {
    ...row,

    source_family:
      "OTHER",

    source_strategy:
      "OFFICIAL_INSTITUTE_DISCOVERY"
  };
}

/*
|--------------------------------------------------------------------------
| MAIN
|--------------------------------------------------------------------------
*/

async function main() {
  console.log("");

  console.log(
    "======================================="
  );

  console.log(
    "ALL COLLEGES FEE SOURCE CLASSIFIER"
  );

  console.log(
    "======================================="
  );

  console.log("");

  const raw =
    await fs.readFile(
      INPUT,
      "utf8"
    );

  const rows =
    JSON.parse(
      raw.replace(
        /^\uFEFF/,
        ""
      )
    );

  if (
    !Array.isArray(rows)
  ) {
    throw new Error(
      "Input JSON must contain an array."
    );
  }

  /*
  |--------------------------------------------------------------------------
  | Optional DB branch presence validation
  |--------------------------------------------------------------------------
  */

  const branchCounts =
    await pool.query(`
      SELECT
        college_id,
        COUNT(*)::int AS branch_count
      FROM branches
      GROUP BY college_id
    `);

  const branchMap =
    new Map(
      branchCounts.rows.map(
        row => [
          String(row.college_id),
          Number(row.branch_count)
        ]
      )
    );

  const results =
    rows.map(
      row => ({
        ...classify(row),

        branch_count:
          branchMap.get(
            String(row.college_id)
          ) || 0
      })
    );

  const josaa =
    results.filter(
      row =>
        row.source_family ===
        "JOSAA"
    );

  const uptac =
    results.filter(
      row =>
        row.source_family ===
        "UPTAC"
    );

  const other =
    results.filter(
      row =>
        row.source_family ===
        "OTHER"
    );

  const completed =
    results.filter(
      row =>
        row.source_family ===
        "COMPLETED"
    );

  await fs.writeFile(
    OUTPUT,
    JSON.stringify(
      results,
      null,
      2
    ),
    "utf8"
  );

  await fs.writeFile(
    JOSAA_OUTPUT,
    JSON.stringify(
      josaa,
      null,
      2
    ),
    "utf8"
  );

  await fs.writeFile(
    UPTAC_OUTPUT,
    JSON.stringify(
      uptac,
      null,
      2
    ),
    "utf8"
  );

  await fs.writeFile(
    OTHER_OUTPUT,
    JSON.stringify(
      other,
      null,
      2
    ),
    "utf8"
  );

  console.log(
    "SOURCE FAMILY SUMMARY"
  );

  console.table([
    {
      source_family:
        "JOSAA",
      count:
        josaa.length
    },
    {
      source_family:
        "UPTAC",
      count:
        uptac.length
    },
    {
      source_family:
        "OTHER",
      count:
        other.length
    },
    {
      source_family:
        "COMPLETED",
      count:
        completed.length
    },
    {
      source_family:
        "TOTAL",
      count:
        results.length
    }
  ]);

  console.log("");

  console.log(
    "JOSAA SAMPLE"
  );

  console.table(
    josaa
      .slice(
        0,
        20
      )
      .map(
        row => ({
          college:
            row.college_name,

          branches:
            row.branch_count,

          strategy:
            row.source_strategy
        })
      )
  );

  console.log("");

  console.log(
    "UPTAC SAMPLE"
  );

  console.table(
    uptac
      .slice(
        0,
        20
      )
      .map(
        row => ({
          college:
            row.college_name,

          branches:
            row.branch_count,

          strategy:
            row.source_strategy
        })
      )
  );

  console.log("");

  console.log(
    "OTHER SAMPLE"
  );

  console.table(
    other
      .slice(
        0,
        20
      )
      .map(
        row => ({
          college:
            row.college_name,

          branches:
            row.branch_count
        })
      )
  );

  console.log("");

  console.log(
    "Saved:",
    OUTPUT
  );

  console.log(
    "Saved:",
    JOSAA_OUTPUT
  );

  console.log(
    "Saved:",
    UPTAC_OUTPUT
  );

  console.log(
    "Saved:",
    OTHER_OUTPUT
  );

  console.log("");

  console.log(
    "DATABASE HAS NOT BEEN MODIFIED."
  );

  await pool.end();
}

main().catch(
  async error => {
    console.error(
      "FAILED:",
      error.message
    );

    try {
      await pool.end();
    } catch {}

    process.exitCode = 1;
  }
);